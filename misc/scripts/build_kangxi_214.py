def main() -> int:
    out: dict[str, dict] = {}
    for number, char, variants, strokes, meaning, onyomi, kunyomi in RADICALS:
        out[str(number)] = {
            "number": number,
            "radical": char,
            "variants": variants,
            "strokes": strokes,
            "meaning_en": meaning,
            "onyomi": onyomi,
            "kunyomi": kunyomi,
        }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2, sort_keys=False)
        f.write("\n")
    print(f"Wrote {len(out)} radicals to {OUT}")
    return 0


